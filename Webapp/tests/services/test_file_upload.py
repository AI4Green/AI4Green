IN_GITHUB_ACTIONS = os.getenv("GITHUB_ACTIONS") == "true"


@pytest.mark.skipif(IN_GITHUB_ACTIONS, reason="Azure blob storage is not setup in CI")
def test_reaction_file_attachment_upload_successful(
    client: FlaskClient, mocker: pytest_mock.MockerFixture
):
    """Tests the response when we try and upload a file attachment to a reaction"""
    login(client)
    # Define form data to send in the request
    form_data = {
        "workgroup": "Test-Workgroup",
        "workbook": "Test-Workbook",
        "reactionID": "TW1-001",
        "file": (io.BytesIO(b"abcdef"), "the test mona lisa.jpg"),
    }
    mock_mime_validation = mocker.patch(
        "sources.services.file_attachments.magic.Magic.from_buffer"
    )
    # we mock the python magic library when checking mimetype
    mock_mime_validation.return_value = "image/jpeg"
    response = client.post(
        "/_upload_experimental_data", data=form_data, content_type="multipart/form-data"
    )
    # assert response is as expected and successful.
    assert response.status_code == 200
    assert len(response.json.get("uploaded_files")) == 1, "1 File should be uploaded"
    assert isinstance(response.json["uploaded_files"][0].get("uuid"), str)
    assert response.json["uploaded_files"][0].get("name") == "the test mona lisa.jpg"
    assert response.json["uploaded_files"][0].get("autogenerated") is False


# --- Attachment validation ---------------------------------------------------
# These pin how BaseFileUploader.file_security_validation treats attachments,
# so the shared validate_upload it now uses can't change what reaction and
# template uploads accept.


def _upload(content: bytes, filename: str) -> FileStorage:
    """An uploaded file, as Werkzeug passes it to a route."""
    return FileStorage(stream=io.BytesIO(content), filename=filename)


@pytest.mark.parametrize(
    "content, filename, sniffed_type, expected",
    [
        (b"abcdef", "picture.jpg", "image/jpeg", "success"),
        (b"a,b\n1,2\n", "data.CSV", "text/csv", "success"),
        (b"abcdef", "", "image/jpeg", "failure"),
        (b"abcdef", "script.exe", "image/jpeg", "failure"),
        (b"abcdef", "picture.jpg", "application/x-dosexec", "failure"),
        (b"a" * (ATTACHMENT_MAX_BYTES + 1), "big.jpg", "image/jpeg", "failure"),
    ],
)
def test_attachment_validation(
    app: Flask,
    mocker: pytest_mock.MockerFixture,
    content: bytes,
    filename: str,
    sniffed_type: str,
    expected: str,
):
    """Attachments need a name, an allowed extension and MIME type, and to be
    no larger than 2 MB."""
    mocker.patch(
        "sources.services.file_attachments.magic.Magic.from_buffer",
        return_value=sniffed_type,
    )
    with app.app_context():
        assert (
            BaseFileUploader.file_security_validation(_upload(content, filename))
            == expected
        )


def test_validate_upload_rewinds_the_stream(
    app: Flask, mocker: pytest_mock.MockerFixture
):
    """After validation the file can be read from the start."""
    mocker.patch(
        "sources.services.file_attachments.magic.Magic.from_buffer",
        return_value="text/csv",
    )
    upload = _upload(b"a,b\n1,2\n", "data.csv")
    with app.app_context():
        assert validate_upload(upload, [".csv"], ["text/csv"], 1024) is None
    assert upload.stream.read() == b"a,b\n1,2\n"
